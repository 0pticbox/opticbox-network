    (
      message_type = 'text'
      and char_length(trim(body)) between 1 and 1000
      and media_path = ''
      and media_size = 0
    )
    or
    (
      message_type = 'video'
      and char_length(body) <= 1000
      and char_length(media_path) between 1 and 2048
      and media_size between 1 and 52428800
    )
  );

