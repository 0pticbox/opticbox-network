create or replace function public.can_view_direct_thread(p_thread uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.direct_threads thread
    where thread.id = p_thread
      and auth.uid() in (thread.user_a, thread.user_b)
      and public.are_friends(thread.user_a, thread.user_b)
      and not exists (
        select 1 from public.blocked_users blocked
        where (blocked.blocker_id = thread.user_a and blocked.blocked_id = thread.user_b)
           or (blocked.blocker_id = thread.user_b and blocked.blocked_id = thread.user_a)
      )
  );
$$;

create or replace function public.can_send_direct_message(p_thread uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select public.can_view_direct_thread(p_thread);
$$;

-- Drop and recreate this RPC so PostgREST sees the exact input parameter name
-- used by the browser: p_other_user.
drop function if exists public.start_direct_thread(uuid);
create function public.start_direct_thread(p_other_user uuid)
returns uuid
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
  v_a uuid;
  v_b uuid;
  v_thread uuid;
begin
  if v_me is null then
    raise exception 'Sign in required';
  end if;
  if p_other_user is null or p_other_user = v_me then
    raise exception 'Choose another member';
  end if;
  if not public.are_friends(v_me, p_other_user) then
    raise exception 'Only accepted friends can start a conversation';
  end if;
  if exists (
    select 1 from public.blocked_users blocked
    where (blocked.blocker_id = v_me and blocked.blocked_id = p_other_user)
       or (blocked.blocker_id = p_other_user and blocked.blocked_id = v_me)
  ) then
    raise exception 'Conversation unavailable';
  end if;

  if v_me::text < p_other_user::text then
    v_a := v_me;
    v_b := p_other_user;
  else
    v_a := p_other_user;
    v_b := v_me;
  end if;

  select thread.id into v_thread
  from public.direct_threads thread
  where thread.user_a = v_a and thread.user_b = v_b;

  if v_thread is null then
    insert into public.direct_threads (user_a, user_b)
    values (v_a, v_b)
    returning id into v_thread;
  end if;

  return v_thread;
end;
$$;

revoke all on function public.can_view_direct_thread(uuid) from public;
revoke all on function public.can_send_direct_message(uuid) from public;
revoke all on function public.start_direct_thread(uuid) from public;
grant execute on function public.can_view_direct_thread(uuid) to authenticated;
grant execute on function public.can_send_direct_message(uuid) to authenticated;
grant execute on function public.start_direct_thread(uuid) to authenticated;

drop policy if exists "Members can read their direct threads" on public.direct_threads;
create policy "Members can read their direct threads"
on public.direct_threads for select
to authenticated
using (public.can_view_direct_thread(id));

drop policy if exists "Members can read their direct messages" on public.direct_messages;
create policy "Members can read their direct messages"
on public.direct_messages for select
to authenticated
using (public.can_view_direct_thread(thread_id));

drop policy if exists "Members can send direct messages" on public.direct_messages;
create policy "Members can send direct messages"
on public.direct_messages for insert
to authenticated
with check (
  sender_id = (select auth.uid())
  and public.can_send_direct_message(thread_id)
);

