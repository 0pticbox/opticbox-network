create or replace function public.block_member(p_other_user uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
begin
  if v_me is null then
    raise exception 'Sign in required';
  end if;
  if p_other_user is null or p_other_user = v_me then
    raise exception 'Choose another member';
  end if;

  insert into public.blocked_users (blocker_id, blocked_id)
  values (v_me, p_other_user)
  on conflict (blocker_id, blocked_id) do nothing;

  delete from public.friendships friendship
  where (friendship.requester_id = v_me and friendship.addressee_id = p_other_user)
     or (friendship.requester_id = p_other_user and friendship.addressee_id = v_me);

  return true;
end;
$$;

create or replace function public.unblock_member(p_other_user uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
begin
  if v_me is null then
    raise exception 'Sign in required';
  end if;
  delete from public.blocked_users
  where blocker_id = v_me and blocked_id = p_other_user;
  return true;
end;
$$;

revoke all on function public.block_member(uuid) from public;
revoke all on function public.unblock_member(uuid) from public;
grant execute on function public.block_member(uuid) to authenticated;
grant execute on function public.unblock_member(uuid) to authenticated;

