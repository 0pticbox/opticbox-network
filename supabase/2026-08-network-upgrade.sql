-- 0PTICBOX Network upgrade: friends, reliable direct threads, blocking, and video messages.
-- Run this entire file once in the Supabase SQL Editor.

begin;

-- Base messaging tables are repeated here so this upgrade also repairs projects
-- where the earlier messaging section was never applied.
create table if not exists public.direct_threads (
  id uuid primary key default gen_random_uuid(),
  user_a uuid not null references public.profiles(id) on delete cascade,
  user_b uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  constraint direct_threads_different_users check (user_a <> user_b),
  constraint direct_threads_canonical_order check (user_a::text < user_b::text),
  constraint direct_threads_unique_pair unique (user_a, user_b)
);

create table if not exists public.blocked_users (
  blocker_id uuid not null references public.profiles(id) on delete cascade,
  blocked_id uuid not null references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  constraint blocked_users_different_users check (blocker_id <> blocked_id)
);

create table if not exists public.direct_messages (
  id bigint generated by default as identity primary key,
  thread_id uuid not null references public.direct_threads(id) on delete cascade,
  sender_id uuid not null references public.profiles(id) on delete cascade,
  body text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists direct_threads_user_a_idx on public.direct_threads (user_a, created_at desc);
create index if not exists direct_threads_user_b_idx on public.direct_threads (user_b, created_at desc);
create index if not exists direct_messages_thread_idx on public.direct_messages (thread_id, created_at);
create index if not exists blocked_users_blocked_idx on public.blocked_users (blocked_id, blocker_id);

alter table public.direct_threads enable row level security;
alter table public.direct_messages enable row level security;
alter table public.blocked_users enable row level security;

drop policy if exists "Members can read relevant block rows" on public.blocked_users;
create policy "Members can read relevant block rows"
on public.blocked_users for select
to authenticated
using ((select auth.uid()) in (blocker_id, blocked_id));

drop policy if exists "Members can create their own blocks" on public.blocked_users;
create policy "Members can create their own blocks"
on public.blocked_users for insert
to authenticated
with check (blocker_id = (select auth.uid()));

drop policy if exists "Members can remove their own blocks" on public.blocked_users;
create policy "Members can remove their own blocks"
on public.blocked_users for delete
to authenticated
using (blocker_id = (select auth.uid()));

-- =============================================================================
-- Friends
-- =============================================================================

create table if not exists public.friendships (
  id uuid primary key default gen_random_uuid(),
  requester_id uuid not null references public.profiles(id) on delete cascade,
  addressee_id uuid not null references public.profiles(id) on delete cascade,
  status text not null default 'pending',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint friendships_different_users check (requester_id <> addressee_id),
  constraint friendships_status_check check (status in ('pending', 'accepted'))
);

create unique index if not exists friendships_unique_pair_idx
on public.friendships (
  least(requester_id::text, addressee_id::text),
  greatest(requester_id::text, addressee_id::text)
);

create index if not exists friendships_requester_idx
on public.friendships (requester_id, status, updated_at desc);

create index if not exists friendships_addressee_idx
on public.friendships (addressee_id, status, updated_at desc);

alter table public.friendships enable row level security;

drop policy if exists "Members can read their friendships" on public.friendships;
create policy "Members can read their friendships"
on public.friendships for select
to authenticated
using (
  (select auth.uid()) in (requester_id, addressee_id)
  and not exists (
    select 1
    from public.blocked_users blocked
    where (blocked.blocker_id = requester_id and blocked.blocked_id = addressee_id)
       or (blocked.blocker_id = addressee_id and blocked.blocked_id = requester_id)
  )
);

grant select on public.friendships to authenticated;

-- Existing unblocked conversations become accepted friendships so the update
-- does not erase the people members were already messaging.
insert into public.friendships (requester_id, addressee_id, status, created_at, updated_at)
select thread.user_a, thread.user_b, 'accepted', thread.created_at, now()
from public.direct_threads thread
where not exists (
  select 1 from public.friendships friendship
  where (friendship.requester_id = thread.user_a and friendship.addressee_id = thread.user_b)
     or (friendship.requester_id = thread.user_b and friendship.addressee_id = thread.user_a)
)
and not exists (
  select 1 from public.blocked_users blocked
  where (blocked.blocker_id = thread.user_a and blocked.blocked_id = thread.user_b)
     or (blocked.blocker_id = thread.user_b and blocked.blocked_id = thread.user_a)
);

create or replace function public.are_friends(p_user_a uuid, p_user_b uuid)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.friendships friendship
    where friendship.status = 'accepted'
      and (
        (friendship.requester_id = p_user_a and friendship.addressee_id = p_user_b)
        or
        (friendship.requester_id = p_user_b and friendship.addressee_id = p_user_a)
      )
  );
$$;

create or replace function public.send_friend_request(p_other_user uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
  v_existing public.friendships%rowtype;
begin
  if v_me is null then
    raise exception 'Sign in required';
  end if;
  if p_other_user is null or p_other_user = v_me then
    raise exception 'Choose another member';
  end if;
  if not exists (select 1 from public.profiles where id = p_other_user) then
    raise exception 'Member not found';
  end if;
  if exists (
    select 1 from public.blocked_users blocked
    where (blocked.blocker_id = v_me and blocked.blocked_id = p_other_user)
       or (blocked.blocker_id = p_other_user and blocked.blocked_id = v_me)
  ) then
    raise exception 'Friend request unavailable';
  end if;

  select friendship.* into v_existing
  from public.friendships friendship
  where (friendship.requester_id = v_me and friendship.addressee_id = p_other_user)
     or (friendship.requester_id = p_other_user and friendship.addressee_id = v_me)
  limit 1;

  if found then
    if v_existing.status = 'accepted' then
      return 'accepted';
    end if;

    -- If the other member already requested the current user, accepting is
    -- automatic instead of creating a second reversed request.
    if v_existing.status = 'pending' and v_existing.addressee_id = v_me then
      update public.friendships
      set status = 'accepted', updated_at = now()
      where id = v_existing.id;
      return 'accepted';
    end if;

    return 'pending';
  end if;

  insert into public.friendships (requester_id, addressee_id, status)
  values (v_me, p_other_user, 'pending');
  return 'pending';
end;
$$;

create or replace function public.respond_friend_request(p_requester uuid, p_accept boolean)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
  v_id uuid;
begin
  if v_me is null then
    raise exception 'Sign in required';
  end if;

  select friendship.id into v_id
  from public.friendships friendship
  where friendship.requester_id = p_requester
    and friendship.addressee_id = v_me
    and friendship.status = 'pending'
  limit 1;

  if v_id is null then
    raise exception 'Friend request not found';
  end if;

  if coalesce(p_accept, false) then
    update public.friendships
    set status = 'accepted', updated_at = now()
    where id = v_id;
  else
    delete from public.friendships where id = v_id;
  end if;

  return true;
end;
$$;

create or replace function public.remove_friend(p_other_user uuid)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_me uuid := auth.uid();
begin
  if v_me is null then
    raise exception 'Sign in required';
  end if;

  delete from public.friendships friendship
  where (friendship.requester_id = v_me and friendship.addressee_id = p_other_user)
     or (friendship.requester_id = p_other_user and friendship.addressee_id = v_me);
  return true;
end;
$$;

create or replace function public.list_friends()
returns table (
  friend_id uuid,
  display_name text,
  avatar_url text,
  profile_status text,
  profile_tagline text,
  friends_since timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    profile.id as friend_id,
    profile.display_name,
    profile.avatar_url,
    profile.status as profile_status,
    profile.profile_tagline,
    friendship.updated_at as friends_since
  from public.friendships friendship
  join public.profiles profile
    on profile.id = case
      when friendship.requester_id = auth.uid() then friendship.addressee_id
      else friendship.requester_id
    end
  where friendship.status = 'accepted'
    and auth.uid() in (friendship.requester_id, friendship.addressee_id)
    and not exists (
      select 1 from public.blocked_users blocked
      where (blocked.blocker_id = friendship.requester_id and blocked.blocked_id = friendship.addressee_id)
         or (blocked.blocker_id = friendship.addressee_id and blocked.blocked_id = friendship.requester_id)
    )
  order by lower(profile.display_name);
$$;

create or replace function public.list_friend_requests()
returns table (
  request_id uuid,
  direction text,
  other_user_id uuid,
  display_name text,
  avatar_url text,
  profile_status text,
  profile_tagline text,
  requested_at timestamptz
)
language sql
stable
security definer
set search_path = ''
as $$
  select
    friendship.id as request_id,
    case when friendship.addressee_id = auth.uid() then 'incoming' else 'outgoing' end as direction,
    profile.id as other_user_id,
    profile.display_name,
    profile.avatar_url,
    profile.status as profile_status,
    profile.profile_tagline,
    friendship.created_at as requested_at
  from public.friendships friendship
  join public.profiles profile
    on profile.id = case
      when friendship.requester_id = auth.uid() then friendship.addressee_id
      else friendship.requester_id
    end
  where friendship.status = 'pending'
    and auth.uid() in (friendship.requester_id, friendship.addressee_id)
    and not exists (
      select 1 from public.blocked_users blocked
      where (blocked.blocker_id = friendship.requester_id and blocked.blocked_id = friendship.addressee_id)
         or (blocked.blocker_id = friendship.addressee_id and blocked.blocked_id = friendship.requester_id)
    )
  order by friendship.created_at desc;
$$;

