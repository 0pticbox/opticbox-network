create or replace function public.message_media_can_read(p_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_parts text[];
  v_thread uuid;
begin
  v_parts := string_to_array(coalesce(p_name, ''), '/');
  if array_length(v_parts, 1) < 3 then return false; end if;
  begin
    v_thread := v_parts[1]::uuid;
  exception when invalid_text_representation then
    return false;
  end;
  return public.can_view_direct_thread(v_thread);
end;
$$;

create or replace function public.message_media_can_write(p_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_parts text[];
  v_thread uuid;
begin
  v_parts := string_to_array(coalesce(p_name, ''), '/');
  if array_length(v_parts, 1) < 3 then return false; end if;
  if v_parts[2] <> auth.uid()::text then return false; end if;
  begin
    v_thread := v_parts[1]::uuid;
  exception when invalid_text_representation then
    return false;
  end;
  return public.can_send_direct_message(v_thread);
end;
$$;

